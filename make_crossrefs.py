"""Write crossrefs.tex so paper.tex and online_appendix.tex can cite each
other's table, figure, and section numbers.

Compile both documents once, run this, then compile both again. The output is
committed, so each PDF also compiles on its own (e.g. on Overleaf) without it.

    lualatex paper && lualatex online_appendix
    python3 make_crossrefs.py
    latexmk -lualatex paper && latexmk -lualatex online_appendix
"""
import re
from pathlib import Path

def numbers(aux):
    """label -> printed number, from a LaTeX .aux file."""
    out = {}
    path = Path(aux)
    if not path.exists():
        return out
    for m in re.finditer(r'\\newlabel\{([^}]*)\}\{\{([^}]*)\}', path.read_text()):
        label, num = m.group(1), m.group(2).strip()
        # Keep plain numbers only (1, 4.2, A12); skip uncaptioned floats etc.
        if re.fullmatch(r'[A-Z]?[0-9]+(\.[0-9]+)*', num):
            out[label] = num
    return out

lines = [
    '% Generated by make_crossrefs.py -- do not edit by hand.',
    '% \\oaref{label}: number of a section, table, or figure in the online appendix.',
    '% \\pref{label}:  number of a section, table, or figure in the paper.',
    '\\newcommand{\\oaref}[1]{\\ifcsname oaref@#1\\endcsname\\csname oaref@#1\\endcsname\\else\\textbf{??}\\fi}',
    '\\newcommand{\\pref}[1]{\\ifcsname pref@#1\\endcsname\\csname pref@#1\\endcsname\\else\\textbf{??}\\fi}',
]
for prefix, aux in [('oaref', 'online_appendix.aux'), ('pref', 'paper.aux')]:
    for label, num in sorted(numbers(aux).items()):
        lines.append('\\expandafter\\def\\csname %s@%s\\endcsname{%s}' % (prefix, label, num))

Path('crossrefs.tex').write_text('\n'.join(lines) + '\n')
print('crossrefs.tex:', len(lines) - 5, 'labels')
